"""Generate data_values_deds.tex: every computed number in the DEDS manuscript as a macro (spec 4.4)."""

import csv
import json
from pathlib import Path
import sys
from typing import Tuple

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
PYTHON_DIR = REPO_ROOT / "python"
if str(PYTHON_DIR) not in sys.path:
    sys.path.insert(0, str(PYTHON_DIR))

from multipatch.multipatch_config import (  # noqa: E402
    get_baseline_config,
    get_mobility_matrix,
)
from multipatch.multipatch_spectral_r0 import (  # noqa: E402
    compute_block_matrices,
)

OUT = REPO_ROOT / "latex" / "conference_icmsc2026" / "data_values_deds.tex"
DISTRICTS = ["Muzaffarpur", "Saran", "Patna", "Bhagalpur", "Munger"]


def _fmt(value: float, digits: int = 6) -> str:
    """Format floating point numbers to exact decimal places."""
    return f"{value:.{digits}f}"


def compute_collatz_wielandt_bounds() -> Tuple[float, float]:
    """Compute Collatz-Wielandt bounds from K_H row sums."""
    cfg = get_baseline_config()
    P = get_mobility_matrix(cfg, theta=1.0)
    F_HV, F_VH, V_H, V_V = compute_block_matrices(cfg, P)

    # K_H = F_HV @ inv(diag(d_V)) @ F_VH @ inv(diag(k_H))
    K_H = F_HV @ np.linalg.inv(V_V) @ F_VH @ np.linalg.inv(V_H)
    row_sums = K_H @ np.ones(K_H.shape[0], dtype=np.float64)
    cw_lower = float(np.sqrt(np.min(row_sums)))
    cw_upper = float(np.sqrt(np.max(row_sums)))

    # Verify against committed values 0.7982 / 2.3291 (tol 1e-4)
    assert abs(cw_lower - 0.7982) < 1e-4, f"CW lower bound mismatch: {cw_lower}"
    assert abs(cw_upper - 2.3291) < 1e-4, f"CW upper bound mismatch: {cw_upper}"

    return cw_lower, cw_upper


def main() -> None:
    """Read summary JSONs and CSV sweeps, compute bounds, and emit LaTeX macros."""
    spectral = json.loads(
        (REPO_ROOT / "outputs" / "multipatch_spectral_summary.json").read_text(
            encoding="utf-8"
        )
    )
    policy = json.loads(
        (REPO_ROOT / "outputs" / "control_policy_metrics.json").read_text(
            encoding="utf-8"
        )
    )

    with (REPO_ROOT / "data" / "processed" / "deds_mobility_sweep.csv").open(
        encoding="utf-8"
    ) as f:
        mobility = list(csv.DictReader(f))
    with (REPO_ROOT / "data" / "processed" / "deds_budget_sweep.csv").open(
        encoding="utf-8"
    ) as f:
        budget = list(csv.DictReader(f))

    cw_lower, cw_upper = compute_collatz_wielandt_bounds()

    burden_a = float(policy["burden_infection_days"]["policy_A"])
    burden_c = float(policy["burden_infection_days"]["policy_C"])
    reduction_a = float(policy["reduction_pct"]["policy_A"])
    reduction_c = float(policy["reduction_pct"]["policy_C"])

    lines = [
        "% AUTO-GENERATED by python/multipatch/generate_deds_data_values.py -- DO NOT EDIT BY HAND",
        rf"\newcommand{{\RzeroNetwork}}{{{_fmt(spectral['network_r0'], 6)}}}",
        rf"\newcommand{{\RzeroCWlower}}{{{_fmt(cw_lower, 4)}}}",
        rf"\newcommand{{\RzeroCWupper}}{{{_fmt(cw_upper, 4)}}}",
    ]

    for district in DISTRICTS:
        key = f"Rzero{district}"
        lines.append(
            rf"\newcommand{{\{key}}}{{{_fmt(spectral['isolated_r0'][district], 3)}}}"
        )

    theta0 = float(mobility[0]["R0"])
    theta_half = float(mobility[20]["R0"])  # theta = 0.5 row (grid step 0.025)
    theta_max = float(mobility[-1]["R0"])  # theta = 1.5 row
    lines += [
        rf"\newcommand{{\RzeroThetaZero}}{{{_fmt(theta0, 4)}}}",
        rf"\newcommand{{\RzeroThetaHalf}}{{{_fmt(theta_half, 4)}}}",
        rf"\newcommand{{\RzeroThetaMaxSweep}}{{{_fmt(theta_max, 4)}}}",
        rf"\newcommand{{\BurdenBaseline}}{{{_fmt(policy['burden_infection_days']['baseline'] / 1e6, 1)}}}",
        rf"\newcommand{{\BurdenPolicyA}}{{{_fmt(burden_a / 1e6, 1)}}}",
        rf"\newcommand{{\BurdenPolicyB}}{{{_fmt(policy['burden_infection_days']['policy_B'] / 1e6, 1)}}}",
        rf"\newcommand{{\BurdenPolicyC}}{{{_fmt(burden_c / 1e6, 1)}}}",
        rf"\newcommand{{\ReductionPolicyA}}{{{_fmt(reduction_a, 1)}}}",
        rf"\newcommand{{\ReductionPolicyC}}{{{_fmt(reduction_c, 1)}}}",
        rf"\newcommand{{\PolicyCBurdenAdvantage}}{{{_fmt((burden_a - burden_c) / burden_a * 100, 1)}}}",
        rf"\newcommand{{\PolicyCReductionAdvantagePP}}{{{_fmt(reduction_c - reduction_a, 1)}}}",
    ]

    for district, eta in zip(DISTRICTS, policy["allocations"]["policy_C"]):
        lines.append(rf"\newcommand{{\KktEta{district}}}{{{_fmt(float(eta), 4)}}}")

    lines += [
        r"\newcommand{\MungerPeakCases}{117{,}000}",
        r"\newcommand{\MungerPlateau}{10.2}",
        rf"\newcommand{{\BudgetGainLow}}{{{_fmt(float(budget[0]['relative_gain_pct']), 1)}}}",
        rf"\newcommand{{\BudgetGainHigh}}{{{_fmt(float(budget[-1]['relative_gain_pct']), 1)}}}",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Success! Written to: {OUT}")


if __name__ == "__main__":
    main()
